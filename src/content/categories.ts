export function getCategoriesByType(type: "ai" | "tool" | "language" | "game" | "kaoyan") {
  return categories
    .filter((c) => c.type === type)
    .sort((a, b) => a.sortOrder - b.sortOrder);
}

export function getCategoryById(id: string) {
  return categories.find((c) => c.id === id);
}
