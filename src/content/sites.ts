// 按分类获取
export function getSitesByCategory(categoryId: string) {
  return sites
    .filter((s) => s.categoryId === categoryId)
    .sort((a, b) => a.sortOrder - b.sortOrder);
}

// 按板块获取所有站点
export function getSitesByType(type: "ai" | "tool" | "language" | "game" | "kaoyan") {
  const catIds = new Set(
    categories
      .filter((c) => c.type === type)
      .map((c) => c.id)
  );
  return sites.filter((s) => catIds.has(s.categoryId));
}

// 按语种获取
export function getSitesByLanguage(lang: string) {
  return sites.filter((s) => s.language === lang);
}

// 获取热门
export function getHotSites(limit = 10) {
  return sites.filter((s) => s.isHot).slice(0, limit);
}

// id 获取
export function getSiteById(id: string) {
  return sites.find((s) => s.id === id);
}
